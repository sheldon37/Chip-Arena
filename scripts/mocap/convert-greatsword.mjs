// Converts the owner's Mixamo "Great Sword Pack" into src/client/mocap/greatsword-clips.ts (development tool).
// The FBX files are licensed Mixamo downloads and are never committed; point the script at an extracted copy:
//   node scripts/mocap/convert-greatsword.mjs <dir with the pack's .fbx files> [--preview <out.ts>]
// The output is deterministic for the same input files. --preview writes every clip of the pack (raw clip time) for the
// visual lab instead (tools/visual-lab: mocap=<clip name>).
import fs from 'node:fs';
import path from 'node:path';
import {loadFbx,calibrate,retarget,encode,leftFootStrike,CHANNELS} from './mixamo-retarget.mjs';

const args=process.argv.slice(2),dir=args[0],previewAt=args.indexOf('--preview'),preview=previewAt>=0?args[previewAt+1]:undefined;
if(!dir||!fs.existsSync(dir)){console.error('usage: node scripts/mocap/convert-greatsword.mjs <pack dir> [--preview out.ts]');process.exit(1);}
const quiet=console.warn;console.warn=()=>{};// FBXLoader warns about every unused FBX property

/** Pack clips used by the game (clip key → file, sampling rate, loop, and for attacks the source contact keys:
 * [start, active start, active end, settled] in source seconds, chosen from the blade-tip sweep). */
const CLIPS={
 // Combat-ready idle (two-hand middle guard).
 idle:{file:'great sword idle.fbx',fps:30,loop:true},
 // Upper body over the game's own gait (legs stay procedural); marks: [left-foot strike] for stride sync.
 walk:{file:'great sword walk.fbx',fps:30,loop:true,strike:true},
 run:{file:'great sword run (2).fbx',fps:30,loop:true,strike:true},
 // Primary combo, alternating like the procedural phrases (attackIndex 1, 3, ... → cutA; 2, 4, ... → cutB). Marks are
 // [start, active start, active end, settled]: the active span is the blade tip crossing the front ±69° arc
 // (WEAPONS.greatsword.arc 2.4) at its sweep speed; settled is back at the guard.
 // cutA: hoist over the right shoulder, stepping diagonal chop down to the front-left.
 cutA:{file:'great sword slash.fbx',fps:30,marks:[0,.60,.76,1.20]},
 // cutB: hips wind far right, flat sweep left-to-right across the front, the blade carried round behind into the guard.
 cutB:{file:'great sword slash (3).fbx',fps:30,marks:[.15,.86,1.02,1.80]},
 // Block raise into the crouched horizontal guard; the guard is held on the clip's last frame.
 block:{file:'great sword blocking.fbx',fps:30,marks:[0,.27,.5]},
 // A successful block: the crouched guard is driven back and recovers.
 blockHit:{file:'great sword impact.fbx',fps:30,marks:[0,.2,.86]},
 // Hitstun: heavy reel back (marks: impact, reel extreme, recovered).
 stagger:{file:'great sword impact (3).fbx',fps:30,marks:[0,.46,1.2]},
};

const load=f=>{const obj=loadFbx(path.join(dir,f));return {obj,clip:obj.animations[0]};};
const files=preview?fs.readdirSync(dir).filter(f=>f.endsWith('.fbx')&&!/^Whiteclown/.test(f)).sort():[...new Set(Object.values(CLIPS).map(c=>c.file))];
const loaded=new Map(files.map(f=>[f,load(f)]));
// Calibrate on the bind pose (every file of the pack shares the same skeleton).
const cal=calibrate(load('great sword idle.fbx').obj);
const entries=preview?files.map(f=>[f.replace(/\.fbx$/,''),{file:f,fps:30,loop:false}]):Object.entries(CLIPS);
let out=`// GENERATED by scripts/mocap/${preview?'convert-greatsword.mjs --preview':'convert-greatsword.mjs'} from the Mixamo Great Sword Pack. Do not edit.\n`+
 `// Channels: ${CHANNELS.length} (src/client/mocap/mocap-clip.ts MOCAP_CHANNELS).\nimport type {MocapClip} from '${preview?'../../src/client/mocap/mocap-clip.js':'./mocap-clip.js'}';\n`+
 `export const ${preview?'PREVIEW_CLIPS':'GREATSWORD_CLIPS'}:Record<string,MocapClip>={\n`;
for(const [key,c] of entries){
 const {obj,clip}=loaded.get(c.file);const rows=retarget(obj,clip,cal,c.fps);
 const m=c.strike?[leftFootStrike(obj,clip)]:c.marks,marks=m?`,marks:[${m.join(',')}]`:'';
 out+=` ${JSON.stringify(key)}:{fps:${c.fps},frames:${rows.length}${c.loop?',loop:true':''}${marks},source:${JSON.stringify(c.file.replace(/\.fbx$/,''))},data:'${encode(rows)}'},\n`;
}
out+='};\n';
const target=preview||path.resolve(path.dirname(new URL(import.meta.url).pathname),'../../src/client/mocap/greatsword-clips.ts');
fs.writeFileSync(target,out);console.warn=quiet;console.log('wrote',target,out.length,'bytes',entries.length,'clips');
