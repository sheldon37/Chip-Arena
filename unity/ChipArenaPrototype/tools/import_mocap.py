"""Extract committed retargeted clip strings; no FBX/purchased source pack is needed.
Usage: python tools/import_mocap.py /path/to/Chip-Arena
Use source commit 05950eaef80ff2483a9c44d898cad98be1a76bbc.
"""
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = '05950eaef80ff2483a9c44d898cad98be1a76bbc'
EXPECTED = {'sword': 'fa29ee1848d0483eeed2fb4a7c6bd42b9aeffe18', 'daggers': '3d3e4899d67e0d431d78d5ae9da5c8721e7f0c5d', 'greatsword': '8ab6228bee68014416e7110764db3e872166f661', 'shield': 'a3f7f51027b2b8e7c1d88dcd7536e23dadac272c'}

def generate(source):
    lines = ['// Generated by tools/import_mocap.py. Private game assets; see ANIMATIONS.md.',
             '// Source: ' + SOURCE, 'namespace ChipArena.UnityPrototype {',
             'public static class CapturedClips {', 'public static readonly CapturedClip[][] Sets = {']
    provenance = []
    for weapon in ['sword', 'daggers', 'greatsword', 'shield']:
        rel = 'src/client/mocap/' + weapon + '-clips.ts'
        raw = (source / rel).read_bytes()
        blob = hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest()
        if blob != EXPECTED[weapon]:
            raise ValueError('Source does not match pinned clip blob: ' + rel)
        provenance.append({'path': rel, 'sha256': hashlib.sha256(raw).hexdigest()})
        lines.append('new CapturedClip[] {')
        count = 0
        for name, obj in re.findall(r'^\s*"(\w+)":(\{.*\}),?$', raw.decode(), re.M):
            obj = re.sub(r'([,{])(\w+):', r'\1"\2":', obj).replace("'", '"')
            c = json.loads(obj)
            def array(key):
                return 'new float[] {' + ','.join(str(x) + 'f' for x in c.get(key, [])) + '}'
            lines.append('new CapturedClip(' + ','.join([
                json.dumps(weapon + '/' + name), json.dumps(c['source']), str(c['fps']), str(c['frames']),
                str(c.get('loop', False)).lower(), array('marks'), array('pace'), json.dumps(c['data'])]) + '),')
            count += 1
        if count < 7:
            raise ValueError('Unexpected clip source: ' + rel)
        lines.append('},')
    lines += ['};', 'public static readonly string[] Names = {"Sword", "Daggers", "Greatsword", "Shield"};', '}', '}']
    (ROOT / 'Assets/ChipArena/Core/CapturedClips.Generated.cs').write_text('\n'.join(lines) + '\n')
    (ROOT / 'tools/mocap-provenance.json').write_text(json.dumps({'commit': SOURCE, 'files': provenance}, indent=2) + '\n')

if __name__ == '__main__':
    generate(Path(sys.argv[1]))
