    // The sleek face gear (owner 2026-11-27: "think we need to update the "masks" section now, they look out of place now with the
    // latest robot armor", then "They look to bulky / wide", then "I need it to be completely new models"; docs/PILOT-BODY-HAIR.md
    // section 6): the MASKS row's helmet, half mask, visor and mask and the suit's ear pods, new models in the sleek pilot suit's
    // style. The owner picked the Sculpted set of two captured in game (2026-11-27): tools/gear/facemodel/sculpted.py models them
    // in Blender (layered white shells, lens slits and seams in the accent light, metal under them); the local hair bank carries them (Core/
    // NativeHairBank.cs version 4) as plates named by their gear ("Helmet: faceplate", ...), each in the head bone's frame, the
    // robot suit's paints (NativeRobotSuit.PlatePaint: the shell the pilot's body colour, the light its accent). Without the bank
    // (or with an older one) the face gear is the robot helmet's (Core/NativeRobotHelm.cs) and the concept's (NativePilotGear) as
    // before. Presentation only: no rule, hit volume, timing or message reads it.
    public static class NativeSleekFace
    {
        /// <summary>The plates' name prefixes: each gear's, and the suit's ear pods (in place of the robot suit's ear modules).</summary>
        public const string Helmet="Helmet: ",HalfMask="Half mask: ",Visor="Visor: ",Mask="Mask: ",Ears="Ears: ";
        private static readonly string[] Gears={Helmet,HalfMask,Visor,Mask,Ears};
        /// <summary>Whether the sleek face gear is worn (set by the presentation when the local bank carries every gear).</summary>
        public static bool On;
        /// <summary>Whether plate `name` is face gear's (else the suit's).</summary>
        public static bool IsFace(string name){foreach(var g in Gears)if(name!=null&&name.StartsWith(g,StringComparison.Ordinal))return true;return false;}
        /// <summary>Whether `plates` carry gear `gear`'s.</summary>
        public static bool Has(NativeHairBank.Plate[] plates,string gear){if(plates!=null)foreach(var p in plates)if(p.Name.StartsWith(gear,StringComparison.Ordinal))return true;return false;}
        /// <summary>Whether `plates` carry all four gears and the ear pods.</summary>
        public static bool HasAll(NativeHairBank.Plate[] plates){foreach(var g in Gears)if(!Has(plates,g))return false;return true;}
        /// <summary>Gear `gear`'s plates as one part on `bone` (the head: CapturedRig.Head for the gear's own models, the robot suit's
        /// Head for its ear pods), named `name`, each vertex in the suit's paints; none without them.</summary>
        public static SheldonSection[] Sections(NativeHairBank.Plate[] plates,string gear,string name,int bone=CapturedRig.Head)
        {
            if(!Has(plates,gear))return Array.Empty<SheldonSection>();
            var k=new Kit();Add(k,k.Part(name,bone),plates,gear);return k.Parts.ToArray();
        }
        /// <summary>Gear `gear`'s plates added to part `s`.</summary>
        internal static void Add(Kit k,SheldonSection s,NativeHairBank.Plate[] plates,string gear)
        {
            foreach(var pl in plates)
            {
                if(!pl.Name.StartsWith(gear,StringComparison.Ordinal))continue;
                int b=s.Positions.Count,n=pl.Paint.Length;
                for(int i=0;i<n;i++)k.Vertex(s,new Vector3(pl.Positions[i*3],pl.Positions[i*3+1],pl.Positions[i*3+2]),new Vector3(pl.Normals[i*3],pl.Normals[i*3+1],pl.Normals[i*3+2]),NativeRobotSuit.PlatePaint(pl.Paint[i]));
                for(int i=0;i+2<pl.Triangles.Length;i+=3)s.Tri(b+pl.Triangles[i],b+pl.Triangles[i+1],b+pl.Triangles[i+2]);
            }
        }

        // ---- the helmet's envelope and each hat's fit (tools/gear/hatfit.py, from the helmet model: the generated block below) ----
        // The envelope is the helmet's outer surface as a star-shaped radius table round the head's middle (EnvCentre): for each
        // azimuth from ahead (0-180 degrees in EnvAzStep steps: the helmet is symmetric) and elevation (EnvEl0 up in EnvElStep steps),
        // the furthest helmet point near that direction. A hat on the helmet (as on the robot helmet, Core/NativeRobotHelm.HatFit:
        // scaled about its HatPivot, lifted and moved ahead) covers as much of the helmet as it covers of the bare head, at the
        // smallest scale (none under its own size) whose lowest lift clears the envelope by 2 mm; the halo keeps its gap over the top.
        // <generated by tools/gear/hatfit.py>
        public static readonly Vector3 EnvCentre=new Vector3(0,.07f,.02f);
        public const int EnvAz=13,EnvEl=13;public const float EnvAzStep=15,EnvEl0=-30,EnvElStep=10;
        private static readonly float[] Envelope={.1533f,.1491f,.1468f,.143f,.1375f,.1399f,.1447f,.1493f,.1519f,.1524f,.1524f,.1528f,.154f,.1503f,.1453f,.1434f,.1353f,.137f,.1393f,.1448f,.1493f,.1519f,.1523f,.1523f,.1528f,.154f,.1435f,.1382f,.1322f,.1255f,.1356f,.1384f,.1438f,.1487f,.151f,.1517f,.1521f,.1524f,.154f,.1332f,.1289f,.1247f,.1208f,.1351f,.1368f,.1424f,.1463f,.1495f,.1513f,.1521f,.1529f,.154f,.1232f,.1202f,.1163f,.1187f,.1329f,.135f,.1399f,.1444f,.1482f,.1506f,.1522f,.1529f,.154f,.1126f,.11f,.112f,.1187f,.1252f,.1304f,.1361f,.1422f,.1475f,.1506f,.1526f,.1533f,.154f,.1078f,.1111f,.1154f,.1155f,.1215f,.1261f,.1329f,.1428f,.1485f,.1515f,.153f,.1534f,.154f,.1078f,.1111f,.1152f,.1152f,.1233f,.1324f,.1397f,.1444f,.1495f,.1522f,.1534f,.1536f,.154f,.1029f,.1062f,.1114f,.1189f,.1277f,.1368f,.1431f,.1489f,.1514f,.153f,.1539f,.1539f,.154f,.1029f,.1061f,.1137f,.1205f,.1301f,.1379f,.1444f,.1491f,.152f,.1534f,.1541f,.1541f,.154f,.1037f,.1068f,.1144f,.1232f,.1301f,.1379f,.1441f,.1492f,.152f,.1534f,.1541f,.1541f,.154f,.1037f,.1066f,.1144f,.1224f,.1275f,.1352f,.1425f,.1484f,.152f,.1534f,.1541f,.1541f,.154f,.1046f,.1066f,.113f,.1179f,.1259f,.1344f,.1404f,.1473f,.1506f,.1531f,.1541f,.1541f,.154f};
        private static readonly string[] FitHats={"cap","beanie","top","wizard","cowboy","crown","cone","antenna","halo"};
        private static readonly float[] FitScale={1.08f,1.085f,1.095f,1.09f,1.085f,1,1.02f,1.045f,1},FitLift={-.0023f,.0068f,.0064f,.0076f,-.003f,-.0145f,.0082f,.0093f,.0116f},FitAhead={-.006f,-.006f,-.008f,-.01f,-.006f,-.006f,-.006f,.012f,0};
        // </generated>
        /// <summary>The envelope's radius toward `p` over its distance from EnvCentre, grown by `grow`: under 1 inside, 1 on it.</summary>
        public static float Inside(Vector3 p,float grow=0)
        {
            var d=p-EnvCentre;float r=d.Length();if(r<1e-6f)return 0;
            float az=MathF.Atan2(MathF.Abs(d.X),d.Z)*180/MathF.PI,el=MathF.Asin(Math.Clamp(d.Y/r,-1f,1f))*180/MathF.PI;
            float fi=Math.Clamp(az/EnvAzStep,0,EnvAz-1.0001f),fj=Math.Clamp((el-EnvEl0)/EnvElStep,0,EnvEl-1.0001f);
            int i=(int)fi,j=(int)fj;float ti=fi-i,tj=fj-j;
            float R=Envelope[i*EnvEl+j]*(1-ti)*(1-tj)+Envelope[(i+1)*EnvEl+j]*ti*(1-tj)+Envelope[i*EnvEl+j+1]*(1-ti)*tj+Envelope[(i+1)*EnvEl+j+1]*ti*tj;
            return r/MathF.Max(R+grow,1e-6f);
        }

        // ---- a hat on the helmet ----
        /// <summary>Hat `hat`'s fit on the sleek helmet: a point p of it (head bone frame) goes to p * scale + move (a hat not made for
        /// the model takes the closed hats' fit).</summary>
        public static void HatFit(string hat,out float scale,out Vector3 move)
        {
            int i=Math.Max(0,Array.IndexOf(FitHats,hat));scale=FitScale[i];move=NativeRobotHelm.HatPivot*(1-scale)+new Vector3(0,FitLift[i],FitAhead[i]);
        }
    }
