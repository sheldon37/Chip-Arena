// Retargets the running attacks of the owner's Explosive "RPG Character Mecanim Animation Pack" (a licensed Unity asset)
// onto the voxel rig for the melee sprint attacks (Core/NativeSprintAttackVisuals): per captured melee weapon its own running take,
// encoded in the melee clips' 64-channel mocap encoding (Core/CapturedClip) and retargeted with that weapon's
// melee-converter options (scripts/mocap/convert-explosive.mjs: grip, one or two hands, mirroring, the guard heading), so
// the attack is posed like the weapon's ground cuts. Development tool, presentation only. The pack's FBX and .meta files
// are never committed: point the script at an extracted copy outside the repository:
//   node unity/ChipArenaConversion/tools/export_pack_sprint_attacks.mjs <pack>/Animations
// It writes only under unity/ChipArenaConversion: Assets/ChipArena/Core/NativePackSprintAttacks.Generated.cs and
// tools/pack-sprint-attacks-provenance.json (each clip's source, frame range, size, marks and the SHA-256 of its encoded
// track and input file, which Tests/SprintAttackChecks recomputes). The same input files give byte-identical output.
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';

const here=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(here,'..'),repo=path.resolve(root,'../..');
const dir=process.argv[2];
if(!dir||!fs.existsSync(path.join(dir,'Armed'))){console.error('usage: node unity/ChipArenaConversion/tools/export_pack_sprint_attacks.mjs <pack>/Animations');process.exit(1);}
const {calibrate,retarget,encode,CHANNELS}=await import(pathToFileURL(path.join(repo,'scripts/mocap/mixamo-retarget.mjs')));
const {loadPackFbx,packRestPose}=await import(pathToFileURL(path.join(repo,'scripts/mocap/explosive-pack.mjs')));
const quiet=console.warn;console.warn=()=>{};// FBXLoader warns about every unused FBX property

const A=f=>`Armed/RPG-Character@Armed-${f}.FBX`,H=f=>`2Hand-Sword/RPG-Character@2Hand-Sword-${f}.FBX`,S=f=>`Armed-Shield/RPG-Character@Armed-Shield-${f}`;
/** Per weapon (Core/NativeSprintAttackVisuals order): the running take and the weapon's guard idle (its heading is carried by the
 * torso, as the melee converter does), with the melee converter's options for that weapon. Sword "Lunging Slash": the
 * one-handed running slash. Daggers "Twin Lunge": the dual running stab in the daggers' reverse grip. Shield "Shoulder
 * Charge": the shield-first charge, mirrored onto the game's shield arm as the shield's cuts are (the take is a loop; the
 * bash at the hit is the rig's, Core/NativeSprintAttackVisuals). Greatsword "Leaping Cleave": the two-handed running overhead. */
const SETS=[
 {name:'sword',file:A('Run-Attack-R1'),idle:{file:A('Idle')},grip:'blade'},
 {name:'daggers',file:A('Run-Attack-Dual'),idle:{file:A('Idle'),grip:'reverse'},grip:'reverse',leftBlade:true},
 {name:'shield',file:S('Run-Forward-Charge.fbx'),idle:{file:S('Idle.fbx'),grip:'shield',mirror:true},grip:'shield',mirror:true,loop:true},
 {name:'greatsword',file:H('Run-Forward-Attack1'),idle:{file:H('Idle')},grip:'blade',twoHand:true},
];
// The pack mixes .fbx and .FBX: names resolve case-insensitively.
const listing=new Map(),resolve=f=>{const d=path.join(dir,path.dirname(f));if(!listing.has(d))listing.set(d,fs.readdirSync(d));
 const hit=listing.get(d).find(n=>n.toLowerCase()===path.basename(f).toLowerCase());if(!hit)throw new Error('missing pack file '+f);return path.join(d,hit);};
const cache=new Map(),load=f=>{if(!cache.has(f))cache.set(f,loadPackFbx(resolve(f)));return cache.get(f);};
const REF='1Hand-Sword/RPG-Character@Sword-Attack-R1.FBX',cals=new Map();
const calFor=(grip,mirror=false)=>{const k=grip+mirror;if(!cals.has(k))cals.set(k,calibrate(packRestPose(resolve(REF)),{mirror,grip}));return cals.get(k);};
function range(file){
 const meta=fs.readFileSync(resolve(file)+'.meta','utf8'),num=k=>{const m=meta.match(new RegExp('\\n\\s+'+k+': (.*)'));if(!m)throw new Error(file+'.meta: no '+k);return Number(m[1]);};
 return {first:num('firstFrame'),last:num('lastFrame'),loop:num('loopTime')===1};
}
const r4=x=>+x.toFixed(4);
/** Marks (clip seconds): [start, end]. The strike timing (lead-in, sweep, follow-through) is measured from the posed blade and
 * kept in Core/MeleeSwing beside the cuts'. */
const marks=(rows,fps)=>[0,r4((rows.length-1)/fps)];
const f32=x=>String(x)+'f';
const lines=['// GENERATED by tools/export_pack_sprint_attacks.mjs from the owner\'s Explosive RPG Character pack: retargeted pose tracks',
 '// only (no FBX, mesh or .meta data). Private game assets; see ANIMATIONS.md. Do not edit.','namespace ChipArena.UnityConversion {',
 'public static class NativePackSprintAttacks {','public static readonly CapturedClip[] Clips = {'];
const provenance=[];
for(const set of SETS){
 const twoHand=!!set.twoHand,mirror=!!set.mirror,opts={mirror,oneHand:!twoHand,bothHands:twoHand,leftBlade:!!set.leftBlade,soften:true,poleTurn:10,splitTwist:true};
 const idle=load(set.idle.file),ir=retarget(idle.obj,idle.clip,calFor(set.idle.grip||'blade',!!set.idle.mirror),30,{...opts,mirror:!!set.idle.mirror,loop:true}),heading=ir.reduce((s,r)=>s+r[0],0)/ir.length;
 const {obj,clip}=load(set.file),rg=range(set.file),fps=60;
 if(rg.loop!==!!set.loop)throw new Error(set.name+': the take '+(rg.loop?'loops':'does not loop'));
 let rows=retarget(obj,clip,calFor(set.grip,mirror),fps,{...opts,heading});
 const a=Math.round(rg.first/30*fps),b=Math.round(rg.last/30*fps);if(b>=rows.length||b-a<4)throw new Error(`${set.name}: frame range ${rg.first}-${rg.last} outside the take`);rows=rows.slice(a,b+1);
 for(const r of rows)for(const v of r)if(!Number.isFinite(v))throw new Error(set.name+': non-finite channel');
 const m=marks(rows,fps),data=encode(rows),source=path.basename(set.file).replace(/^RPG-Character@|\.fbx$/gi,'');
 lines.push('new CapturedClip('+[JSON.stringify('sprint/'+set.name),JSON.stringify(source+(mirror?' (mirrored)':'')),fps,rows.length,false,'new float[] {'+m.map(f32).join(',')+'}','new float[] {}',JSON.stringify(data)].join(',')+'),');
 provenance.push({clip:'sprint/'+set.name,source:source+(mirror?' (mirrored)':''),range:[rg.first,rg.last],fps,frames:rows.length,marks:m,heading:r4(heading),sha256:createHash('sha256').update(data).digest('hex'),input:createHash('sha256').update(fs.readFileSync(resolve(set.file))).digest('hex')});
 console.log(set.name,'marks',m.join(' '),'heading',heading.toFixed(3));
}
lines.push('};','public static readonly string[] Names = {'+SETS.map(s=>JSON.stringify(s.name)).join(', ')+'};','}','}');
fs.writeFileSync(path.join(root,'Assets/ChipArena/Core/NativePackSprintAttacks.Generated.cs'),lines.join('\n')+'\n');
fs.writeFileSync(path.join(root,'tools/pack-sprint-attacks-provenance.json'),JSON.stringify({pack:'Explosive RPG Character Mecanim Animation Pack (owner licence; FBX never committed)',channels:CHANNELS.length,quantum:1/256,clips:provenance},null,1)+'\n');
console.warn=quiet;console.log('wrote',provenance.length,'sprint attack clips');
