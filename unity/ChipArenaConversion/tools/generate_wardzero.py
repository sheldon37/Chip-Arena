#!/usr/bin/env python3
"""Import the frozen Ward Zero geometry and generate supported, two-floor navigation."""
import hashlib
import importlib.util
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
spec = importlib.util.spec_from_file_location('ward', ROOT / 'docs/arenas/scripts/wardzero_m1.py')
ward = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ward)
data = ward.draft()
m = data['maps'][0]
resource = ROOT / 'unity/ChipArenaConversion/Assets/Conversion/Resources'
content = json.loads((resource / 'UnityMaps.json').read_text())
legacy = next(x for x in json.loads((resource / 'GameContent.json').read_text())['maps'] if x['id'] == 'siren')
m['music'], m['rotation'] = legacy['music'], legacy['rotation']

def pos(x, y, z):
    return dict(x=round(x, 4), y=round(y, 4), z=round(z, 4))

def crosses(a, b, c, size, margin=.45):
    low, high = 0., 1.
    for k in 'xyz':
        lo, hi = c[k] - size[k]/2 - margin, c[k] + size[k]/2 + margin
        d = b[k] - a[k]
        if abs(d) < 1e-9:
            if not lo <= a[k] <= hi:
                return False
        else:
            u, v = sorted(((lo-a[k])/d, (hi-a[k])/d))
            low, high = max(low, u), min(high, v)
            if low > high:
                return False
    return True

def gates(a, b):
    return [h['id'] for h in m['hazards'] if any(crosses(a, b, z['center'], z['size']) for z in (h['zones'] if h['kind']=='burner' else [h]))]

nodes, cells, links = [], {}, []
for x in range(math.ceil(m['bounds']['minX']), math.floor(m['bounds']['maxX'])):
    for z in range(math.ceil(m['bounds']['minZ']), math.floor(m['bounds']['maxZ'])):
        for y in ward.surfaces(x+.5, z+.5):
            if y < -.01 or y > ward.ROOF-1 or ward.blocked(x+.5, z+.5, y):
                continue
            n = dict(id=f'siren-nav-{x},{z},{y:g}', pos=pos(x+.5,y+.9,z+.5), layer=1 if y>=ward.L1-.01 else 0, safe=False)
            nodes.append(n)
            cells.setdefault((x,z), []).append(n)

def supported(a,b):
    p,q=a['pos'],b['pos']
    if abs(p['y']-q['y'])>.6:
        return False
    for i in range(1,9):
        t=i/8
        x,y,z=(p[k]+(q[k]-p[k])*t for k in 'xyz')
        floor=y-.9
        if not any(abs(top-floor)<.18 and not ward.blocked(x,z,top) for top in ward.surfaces(x,z)):
            return False
    return True

def link(a,b,kind,identifier=None):
    links.append(dict(id=identifier or a['id']+'>'+b['id'],a=a['id'],b=b['id'],kind=kind,requires=[],after=[],hazards=gates(a['pos'],b['pos'])))

for (x,z), rows in cells.items():
    for a in rows:
        for dx,dz in ((1,0),(0,1)):
            for b in cells.get((x+dx,z+dz),[]):
                if supported(a,b):
                    link(a,b,'stair' if abs(a['pos']['y']-b['pos']['y'])>.05 else 'walk')

def nearest(p):
    eligible=[n for n in nodes if abs(n['pos']['y']-.9-p['y'])<.6]
    return min(eligible,key=lambda n:sum((n['pos'][k]-p[k]-(.9 if k=='y' else 0))**2 for k in 'xyz'))

for drop in m['navHints']['drops']:
    link(nearest(drop['a']),nearest(drop['b']),'drop',drop['id'])
for safe in m['navHints']['safe']:
    nearest(safe['at'])['safe']=True
m['nav']=dict(nodes=nodes,links=links)
content['maps']=[x for x in content['maps'] if x['id']!='siren']+[m]
(resource/'UnityMaps.json').write_text(json.dumps(content,separators=(',',':'))+'\n')
pve=json.loads((resource/'PveContent.json').read_text())
pve.update(data['pve'])
pve['adds']=[a for a in pve['adds'] if a['id']!='hulk']+[dict(id='hulk',attack='smash',hp=1600,damage=32,walk=.75,run=1.15,reach=3,startRange=2.6,hit=1.1,cycle=3.4,lunge=.15,impulse=900,reward=300,limbFrac=.55,headFrac=.6,stagger=.2,smashRadius=2.8)]
for table in pve['waves'][1:]+pve['bossMix']:
    table['mix']=[x for x in table['mix'] if x['name']!='hulk']+[dict(name='hulk',value=.06)]

(resource/'PveContent.json').write_text(json.dumps(pve,separators=(',',':'))+'\n')
lockpath=ROOT/'unity/ChipArenaConversion/tools/asset-lock.json'
lock=json.loads(lockpath.read_text())
for name in ('UnityMaps.json','PveContent.json'):
    path=resource/name
    raw=path.read_bytes()
    rel='Assets/Conversion/Resources/'+name
    lock['assets']=[a for a in lock['assets'] if a['path']!=rel]+[dict(path=rel,bytes=len(raw),gitBlob=hashlib.sha1(b'blob '+str(len(raw)).encode()+b'\0'+raw).hexdigest(),source='Generated by tools/generate_wardzero.py; retains other map content')]
lockpath.write_text(json.dumps(lock,indent=2)+'\n')
print(f"Ward Zero: {len(m['blocks'])} blocks, {len(nodes)} nodes, {len(links)} links, {len(pve['entries'])} entries")
