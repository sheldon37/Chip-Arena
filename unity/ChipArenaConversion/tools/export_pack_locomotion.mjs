// Retargets the directional locomotion loops of the owner's Explosive "RPG Character Mecanim Animation Pack" (a licensed
// Unity asset) onto the voxel rig for the captured melee route's travel carry (Core/NativePackLocomotion): per melee weapon
// the slow walk, the walk and seven strafe directions, and the run in eight directions, so strafing and backpedalling show
// real strafe and backpedal cycles under the procedural feet. Development tool, presentation only. The pack's FBX and
// .meta files are never committed: point the script at an extracted copy outside the repository:
//   node unity/ChipArenaConversion/tools/export_pack_locomotion.mjs <pack>/Animations
// It writes only under unity/ChipArenaConversion: Assets/ChipArena/Core/NativePackLocomotion.Generated.cs (retargeted pose
// tracks in the 64-channel mocap encoding, Core/CapturedClip) and tools/pack-locomotion-provenance.json (each clip's source,
// frame range, size, left-foot strike and the SHA-256 of its track, which Tests/PackLocomotionChecks recomputes). The same
// input files give byte-identical output. The retarget is the melee converter's (scripts/mocap/convert-explosive.mjs walk
// and run carries: heading left to the gait, the left foot's strike as phase 0), so the clips phase to the gait's stride.
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';

const here=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(here,'..'),repo=path.resolve(root,'../..');
const dir=process.argv[2];
if(!dir||!fs.existsSync(path.join(dir,'Armed'))){console.error('usage: node unity/ChipArenaConversion/tools/export_pack_locomotion.mjs <pack>/Animations');process.exit(1);}
const {calibrate,retarget,encode,leftFootStrike,CHANNELS}=await import(pathToFileURL(path.join(repo,'scripts/mocap/mixamo-retarget.mjs')));
const {loadPackFbx,packRestPose}=await import(pathToFileURL(path.join(repo,'scripts/mocap/explosive-pack.mjs')));
const quiet=console.warn;console.warn=()=>{};// FBXLoader warns about every unused FBX property

const A=f=>`Armed/RPG-Character@Armed-${f}.FBX`,S=f=>`Armed-Shield/RPG-Character@Armed-Shield-${f}.fbx`,H=f=>`2Hand-Sword/RPG-Character@2Hand-Sword-${f}.FBX`;
/** Sets in Core/NativeLocomotionRules order (the melee converter's own sets): the daggers in a reverse grip, the shield the
 * pack's left-arm shield read mirrored onto the right arm (its left and right clips swap), the greatsword two-handed at a
 * walk and trailing the blade low in the main hand at a run, as its captured carries. */
const SETS=[
 {name:'sword',clips:A},
 {name:'daggers',clips:A,grip:'reverse',leftBlade:true},
 {name:'greatsword',clips:H,twoHand:true,runOneHand:true},
 {name:'shield',clips:S,grip:'shield',mirror:true},
];
/** Slots: slow (Walk-Slow), then the walk family by direction from the facing, counter-clockwise (to the rig's left) in
 * 45 degree steps (Walk ahead, then the strafes), then the run family in the same order. */
const DIRS=['Forward','Forward-Left','Left','Backward-Left','Backward','Backward-Right','Right','Forward-Right'];
const SLOTS=['slow',...DIRS.map(d=>'walk-'+d.toLowerCase()),...DIRS.map(d=>'run-'+d.toLowerCase())];
const swap=d=>d.replace(/Left|Right/g,m=>m==='Left'?'Right':'Left');
function fileOf(set,slot){
 if(slot==='slow')return set.clips('Walk-Slow');
 const [family,...rest]=slot.split('-'),d=DIRS[DIRS.findIndex(x=>x.toLowerCase()===rest.join('-'))],dd=set.mirror?swap(d):d;
 if(family==='walk')return set.clips(dd==='Forward'?'Walk':'Strafe-'+dd);
 return set.clips('Run-'+dd);
}
const listing=new Map(),resolve=f=>{const d=path.join(dir,path.dirname(f));if(!listing.has(d))listing.set(d,fs.readdirSync(d));
 const hit=listing.get(d).find(n=>n.toLowerCase()===path.basename(f).toLowerCase());if(!hit)throw new Error('missing pack file '+f);return path.join(d,hit);};
const cache=new Map(),load=f=>{if(!cache.has(f))cache.set(f,loadPackFbx(resolve(f)));return cache.get(f);};
const REF='1Hand-Sword/RPG-Character@Sword-Attack-R1.FBX',cals=new Map();
const calFor=(mirror,grip)=>{const k=mirror+grip;if(!cals.has(k))cals.set(k,calibrate(packRestPose(resolve(REF)),{mirror,grip}));return cals.get(k);};
function range(file){
 const meta=fs.readFileSync(resolve(file)+'.meta','utf8'),num=k=>{const m=meta.match(new RegExp('\\n\\s+'+k+': (.*)'));if(!m)throw new Error(file+'.meta: no '+k);return Number(m[1]);};
 return {first:num('firstFrame'),last:num('lastFrame'),loop:num('loopTime')===1};
}
const lines=['// GENERATED by tools/export_pack_locomotion.mjs from the owner\'s Explosive RPG Character pack: retargeted pose tracks only',
 '// (no FBX, mesh or .meta data). Private game assets; see ANIMATIONS.md. Do not edit.','namespace ChipArena.UnityConversion {',
 'public static class NativePackLocomotion {','public static readonly CapturedClip[][] Sets = {'];
const provenance=[];
for(const set of SETS){
 const grip=set.grip||'blade',mirror=!!set.mirror,cal=calFor(mirror,grip);
 lines.push('new CapturedClip[] {');
 for(const slot of SLOTS){
  const file=fileOf(set,slot),{obj,clip}=load(file),rg=range(file),fps=30,oneHand=!set.twoHand||(set.runOneHand&&slot.startsWith('run'));
  if(!rg.loop)throw new Error(file+': not a loop');
  let rows=retarget(obj,clip,cal,fps,{mirror,oneHand,bothHands:!oneHand,leftBlade:!!set.leftBlade,soften:true,poleTurn:10,splitTwist:true,heading:0,loop:true});
  const a=Math.round(rg.first/30*fps),b=Math.round(rg.last/30*fps);if(b>=rows.length||b-a<4)throw new Error(`${set.name}/${slot}: frame range outside the take`);rows=rows.slice(a,b+1);
  for(const r of rows)for(const v of r)if(!Number.isFinite(v))throw new Error(`${set.name}/${slot}: non-finite channel`);
  const strike=+Math.min(leftFootStrike(obj,clip,60,{mirror}),(rows.length-1)/fps).toFixed(4),data=encode(rows),source=path.basename(file).replace(/^RPG-Character@|\.fbx$/gi,'')+(mirror?' (mirrored)':'');
  lines.push('new CapturedClip('+[JSON.stringify(set.name+'/'+slot),JSON.stringify(source),fps,rows.length,true,'new float[] {'+String(strike)+'f}','new float[] {}',JSON.stringify(data)].join(',')+'),');
  provenance.push({clip:set.name+'/'+slot,source,range:[rg.first,rg.last],fps,frames:rows.length,loop:true,strike,sha256:createHash('sha256').update(data).digest('hex'),input:createHash('sha256').update(fs.readFileSync(resolve(file))).digest('hex')});
 }
 lines.push('},');
 console.log(set.name,SLOTS.length,'loops');
}
lines.push('};','public static readonly string[] Names = {'+SETS.map(s=>JSON.stringify(s.name)).join(', ')+'};','public static readonly string[] Slots = {'+SLOTS.map(s=>JSON.stringify(s)).join(', ')+'};','}','}');
fs.writeFileSync(path.join(root,'Assets/ChipArena/Core/NativePackLocomotion.Generated.cs'),lines.join('\n')+'\n');
fs.writeFileSync(path.join(root,'tools/pack-locomotion-provenance.json'),JSON.stringify({pack:'Explosive RPG Character Mecanim Animation Pack (owner licence; FBX never committed)',channels:CHANNELS.length,quantum:1/256,clips:provenance},null,1)+'\n');
console.warn=quiet;console.log('wrote',provenance.length,'locomotion loops');
